import { Router } from "express";

import {
  getOrganizationAuditLogsController,
  getUserAuditLogsController,
  getEntityAuditLogsController,
  getAuditLogByIdController,
} from "../controllers/auditLog.controller";

import { authenticate } from "../middleware/auth.middleware";
import { authorize } from "../middleware/rbac.middleware";
import { UserRole } from "../types/auth.types";

const router = Router();

// ==========================================
// ALL AUDIT LOG ROUTES REQUIRE AUTHENTICATION
// ==========================================

router.use(authenticate);

// ==========================================
// GET ORGANIZATION AUDIT LOGS
// OWNER / ADMIN ONLY
// ==========================================

router.get(
  "/organizations/:organizationId/audit-logs",
  authorize(
    UserRole.OWNER,
    UserRole.ADMIN
  ),
  getOrganizationAuditLogsController
);

// ==========================================
// GET CURRENT USER'S AUDIT LOGS
// User ID ownership is checked in the controller.
// ==========================================

router.get(
  "/users/:userId/audit-logs",
  getUserAuditLogsController
);

// ==========================================
// GET ENTITY AUDIT LOGS
// OWNER / ADMIN ONLY
// ==========================================

router.get(
  "/organizations/:organizationId/audit-logs/entity/:entityType/:entityId",
  authorize(
    UserRole.OWNER,
    UserRole.ADMIN
  ),
  getEntityAuditLogsController
);

// ==========================================
// GET SINGLE AUDIT LOG
// OWNER / ADMIN ONLY
// ==========================================

router.get(
  "/organizations/:organizationId/audit-logs/:auditLogId",
  authorize(
    UserRole.OWNER,
    UserRole.ADMIN
  ),
  getAuditLogByIdController
);

// No public POST endpoint:
// audit entries should be generated by backend business services.

export default router;